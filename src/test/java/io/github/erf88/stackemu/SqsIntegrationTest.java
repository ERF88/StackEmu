package io.github.erf88.stackemu;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertTrue;

import io.github.erf88.stackemu.application.sqs.SqsMessagePort;
import io.github.erf88.stackemu.application.sqs.SqsQueuePort;
import io.quarkus.test.junit.QuarkusTest;
import jakarta.inject.Inject;
import java.util.List;
import java.util.Map;
import java.util.Optional;
import java.util.UUID;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.condition.EnabledIfEnvironmentVariable;
import software.amazon.awssdk.services.sqs.SqsClient;

/** Real local MiniStack coverage. Each test removes only queues it created. */
@QuarkusTest
@EnabledIfEnvironmentVariable(named = "STACKEMU_INTEGRATION", matches = "true")
class SqsIntegrationTest {
  @Inject SqsClient client;
  @Inject SqsQueuePort queues;
  @Inject SqsMessagePort messages;

  private final List<String> created = new java.util.ArrayList<>();

  @AfterEach
  void removeOwnQueues() {
    for (String queue : created) {
      try {
        client.deleteQueue(
            request ->
                request.queueUrl(client.getQueueUrl(url -> url.queueName(queue)).queueUrl()));
      } catch (RuntimeException ignored) {
        // Test cleanup never targets queues not generated by this fixture.
      }
    }
  }

  @Test
  void standardQueueSendsReceivesAtZeroVisibilityAndDeletesBatch() {
    String queue = create("messages");
    messages.send(
        queue,
        new SqsMessagePort.OutboundMessage("first", Map.of(), Optional.empty(), Optional.empty()));
    messages.send(
        queue,
        new SqsMessagePort.OutboundMessage("second", Map.of(), Optional.empty(), Optional.empty()));

    var received = messages.receive(queue, 10, 0);
    assertEquals(2, received.size());
    assertTrue(received.stream().allMatch(message -> !message.receiptHandle().isBlank()));
    var result =
        messages.deleteBatch(
            queue, received.stream().map(SqsMessagePort.ReceivedMessage::receiptHandle).toList());
    assertEquals(2, result.succeededIds().size());
    assertTrue(result.failures().isEmpty());
  }

  @Test
  void fifoQueueAndCompatibleDlqAreRecorded() {
    String deadLetter = create("dead-letter.fifo");
    String source = create("source.fifo");
    queues.updateQueue(
        source,
        queues.getQueue(source).settings(),
        Map.of("scope", "integration"),
        Optional.of(new SqsQueuePort.RedrivePolicy(deadLetter, 5)));

    var details = queues.getQueue(source);
    assertTrue(details.fifo());
    assertEquals("integration", details.tags().get("scope"));
    assertTrue(details.redrivePolicy().isPresent());
    assertEquals(deadLetter, details.redrivePolicy().get().deadLetterQueueName());
  }

  private String create(String suffix) {
    String name = "stackemu-sqs-" + UUID.randomUUID() + "-" + suffix;
    queues.createQueue(
        new SqsQueuePort.CreateQueue(
            name, new SqsQueuePort.Settings(30, 345600, 0, 262144, 0, false, true), Map.of()));
    created.add(name);
    assertFalse(queues.getQueue(name).arn().isBlank());
    return name;
  }
}
