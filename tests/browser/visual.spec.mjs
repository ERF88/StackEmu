import { test, expect } from "@playwright/test";
import { readFile } from "node:fs/promises";
import { createHash } from "node:crypto";

if (process.platform !== "linux") {
  throw new Error(
    "Run visual baselines in the documented Playwright Linux container, not on the host OS.",
  );
}

const scenes = {
  overview: "/",
  service: "/s3",
  connection: "/connection",
  gallery: "/components",
  form: "/s3/write?action=bucket",
  bucket: "/s3/bucket?bucket=visual-example&prefix=samples%2F",
  object: "/s3/object?bucket=visual-example&key=samples%2Fa%C3%A7%C3%A3o%20%2B%25.txt",
  unavailable: "/s3",
  error: "/s3/bucket?bucket=visual-example",
};

for (const language of ["en", "pt-BR"]) {
  for (const theme of ["dark", "light"]) {
    for (const width of [1440, 390]) {
      for (const [scene, path] of Object.entries(scenes)) {
        test(`visual contracts: ${scene}, ${language}, ${theme}, ${width}`, async ({
          page,
          request,
        }) => {
          await page.setViewportSize({ width, height: width === 390 ? 844 : 1000 });
          await page.emulateMedia({ colorScheme: theme, reducedMotion: "reduce" });
          const policy = (await request.get("/components")).headers()["content-security-policy"];
          expect(policy).toBeTruthy();
          let html;
          let status = 200;
          const errors = [];
          page.on("pageerror", (error) => errors.push(error.message));
          page.on("console", (message) => {
            if (
              message.type() === "error" &&
              /Content Security Policy|Refused to|blocked by|net::ERR_|status of 404/.test(
                message.text(),
              )
            )
              errors.push(message.text());
          });
          await page.route("**/*", async (route) =>
            route.request().isNavigationRequest()
              ? route.fulfill({
                  status,
                  contentType: "text/html; charset=utf-8",
                  headers: { "Content-Security-Policy": policy },
                  body: html,
                })
              : // In this fixture setup Chromium rejects local-network asset loads after a
                // fulfilled navigation. Proxy actual HTTP asset responses; change no security flags.
                route.fulfill({ response: await route.fetch() }),
          );
          // Rendered Qute fixtures are generated by Java verification, not fabricated HTML.
          html = await readFile(
            new URL(
              `../../work/browser-fixtures/${scene}-${language}-${theme}.html`,
              import.meta.url,
            ),
            "utf8",
          );
          status = scene === "error" ? 503 : 200;
          await page.mouse.move(0, 0);
          await page.goto(
            `${path}${path.includes("?") ? "&" : "?"}lang=${language}&theme=${theme}`,
          );
          await expect(page.locator("html")).toHaveAttribute("lang", language);
          await expect(page.locator("html")).toHaveAttribute("data-theme", theme);
          await expect(page.locator(".sidebar")).toHaveCSS("display", "flex");
          if (width === 390) {
            const sidebar = await page.locator(".sidebar").boundingBox();
            const workspace = await page.locator(".workspace").boundingBox();
            expect(Math.abs(workspace.y - sidebar.y - sidebar.height)).toBeLessThanOrEqual(1);
          }
          if (scene === "overview") {
            for (const [selector, attribute] of [
              ['link[rel="stylesheet"]', "href"],
              ['link[rel="icon"]', "href"],
              ['script[src^="/app.js?v="]', "src"],
            ]) {
              const href = await page.locator(selector).getAttribute(attribute);
              const response = await request.get(href);
              expect(response.status()).toBe(200);
              expect(href.split("?v=")[1]).toBe(
                createHash("sha256")
                  .update(await response.body())
                  .digest("hex"),
              );
            }
          }
          expect(
            await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth),
          ).toBe(true);
          if (scene === "gallery") {
            // The first full-page capture can settle this gallery's layout by 3px.
            // Discard only this preparation frame; compare the complete full-page baseline below.
            await page.screenshot({ fullPage: true, animations: "disabled", caret: "hide" });
          }
          await expect(page).toHaveScreenshot(`${scene}-${language}-${theme}-${width}.png`, {
            fullPage: true,
          });
          if (scene === "gallery") {
            const action = page.locator("#gallery-primary");
            await action.hover();
            await expect(page.locator(".gallery-examples")).toHaveScreenshot(
              `gallery-hover-${language}-${theme}-${width}.png`,
            );
            await action.focus();
            await page.keyboard.press("Tab");
            await page.keyboard.press("Shift+Tab");
            await expect(action).toBeFocused();
            await expect(page.locator(".gallery-examples")).toHaveScreenshot(
              `gallery-focus-${language}-${theme}-${width}.png`,
            );
            const checkbox = page.getByRole("checkbox");
            await checkbox.focus();
            await page.keyboard.press("Space");
            await expect(checkbox).toBeChecked();
            await page.keyboard.press("Space");
            await expect(checkbox).not.toBeChecked();
            const disclosure = page.locator("details");
            await disclosure.locator("summary").focus();
            await page.keyboard.press("Enter");
            await expect(disclosure).toHaveAttribute("open", "");
            await page.keyboard.press("Space");
            await expect(disclosure).not.toHaveAttribute("open");
          }
          expect(errors).toEqual([]);
        });
      }
    }
  }
}
